package fixer

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

// AutoFixer safely manages applying suggested overrides into docker-compose.override.yml.
type AutoFixer struct {
	basePath string
}

// NewAutoFixer creates a fixer targeting the directory containing the compose stack.
func NewAutoFixer(basePath string) *AutoFixer {
	if basePath == "" {
		basePath = "."
	}
	return &AutoFixer{basePath: basePath}
}

// OverrideFilePath returns the target docker-compose.override.yml path.
func (f *AutoFixer) OverrideFilePath() string {
	return filepath.Join(f.basePath, "docker-compose.override.yml")
}

// ApplyOverride writes or merges the suggested YAML block into docker-compose.override.yml.
func (f *AutoFixer) ApplyOverride(suggestedYAML string) (string, error) {
	if strings.TrimSpace(suggestedYAML) == "" {
		return "", fmt.Errorf("empty override snippet")
	}

	overridePath := f.OverrideFilePath()

	// Parse incoming suggested YAML
	var incomingNode yaml.Node
	if err := yaml.Unmarshal([]byte(suggestedYAML), &incomingNode); err != nil {
		return "", fmt.Errorf("invalid suggested YAML: %w", err)
	}

	// If file exists, back it up and merge
	if info, err := os.Stat(overridePath); err == nil && !info.IsDir() {
		existingBytes, err := os.ReadFile(overridePath)
		if err != nil {
			return "", fmt.Errorf("failed to read existing override file: %w", err)
		}

		// Create backup
		backupPath := overridePath + ".bak"
		if err := os.WriteFile(backupPath, existingBytes, 0644); err != nil {
			return "", fmt.Errorf("failed to create backup file %s: %w", backupPath, err)
		}

		var existingNode yaml.Node
		if err := yaml.Unmarshal(existingBytes, &existingNode); err != nil {
			return "", fmt.Errorf("failed to parse existing override YAML: %w", err)
		}

		mergedBytes, err := mergeYAMLNodes(&existingNode, &incomingNode)
		if err != nil {
			return "", fmt.Errorf("failed to merge YAML: %w", err)
		}

		if err := os.WriteFile(overridePath, mergedBytes, 0644); err != nil {
			return "", fmt.Errorf("failed to write updated override file: %w", err)
		}
		return fmt.Sprintf("Updated %s (backup saved to %s)", overridePath, backupPath), nil
	}

	// Create new file
	header := "# Generated by StackLoom Pre-Flight Auto-Fixer\n"
	content := header + strings.TrimSpace(suggestedYAML) + "\n"
	if err := os.WriteFile(overridePath, []byte(content), 0644); err != nil {
		return "", fmt.Errorf("failed to create %s: %w", overridePath, err)
	}

	return fmt.Sprintf("Created %s with suggested configuration", overridePath), nil
}

func mergeYAMLNodes(existing, incoming *yaml.Node) ([]byte, error) {
	// Simple map-level merge in yaml.Node AST
	var existingMap map[string]interface{}
	var incomingMap map[string]interface{}

	existingBytes, err := yaml.Marshal(existing)
	if err != nil {
		return nil, err
	}
	_ = yaml.Unmarshal(existingBytes, &existingMap)

	incomingBytes, err := yaml.Marshal(incoming)
	if err != nil {
		return nil, err
	}
	_ = yaml.Unmarshal(incomingBytes, &incomingMap)

	if existingMap == nil {
		existingMap = make(map[string]interface{})
	}

	deepMergeMaps(existingMap, incomingMap)

	return yaml.Marshal(existingMap)
}

func deepMergeMaps(dst, src map[string]interface{}) {
	for k, v := range src {
		if vMap, ok := v.(map[string]interface{}); ok {
			if dstMap, exists := dst[k].(map[string]interface{}); exists {
				deepMergeMaps(dstMap, vMap)
				continue
			}
		}
		dst[k] = v
	}
}
